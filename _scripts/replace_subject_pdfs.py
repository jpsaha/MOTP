
#!/usr/bin/env python3
"""
Replace subject-wise PDFs in MOTP using PDFs generated by the RMO build.

Mapping:
    prooly/11rmo/pdf/alg_yr.pdf
        -> MOTP/assets/pdf/Algebra/alg_yr.pdf

    prooly/11rmo/pdf/alg_topic.pdf
        -> MOTP/assets/pdf/Algebra/alg_topic.pdf

    prooly/11rmo/pdf/comb_yr.pdf
        -> MOTP/assets/pdf/Combinatorics/comb_yr.pdf

    prooly/11rmo/pdf/comb_topic.pdf
        -> MOTP/assets/pdf/Combinatorics/comb_topic.pdf

    prooly/11rmo/pdf/geo_yr.pdf
        -> MOTP/assets/pdf/Geometry/geo_yr.pdf

    prooly/11rmo/pdf/geo_topic.pdf
        -> MOTP/assets/pdf/Geometry/geo_topic.pdf

    prooly/11rmo/pdf/nt_yr.pdf
        -> MOTP/assets/pdf/NumberTheory/nt_yr.pdf

    prooly/11rmo/pdf/nt_topic.pdf
        -> MOTP/assets/pdf/NumberTheory/nt_topic.pdf

Behavior:
    - Dry-run by default.
    - --apply performs actual replacements.
    - SHA-256 hashes determine whether contents differ.
    - Identical files are skipped.
    - Only existing destination files are replaced.
    - Missing destination files are not added.
    - Destination-only PDFs are preserved.
"""

import argparse
import hashlib
import shutil
import sys
from pathlib import Path


# ============================================================
# Configuration
# ============================================================

SCRIPT_DIR = Path(__file__).resolve().parents[2]

PROOLY_ROOT = SCRIPT_DIR / "prooly"
MOTP_ROOT = SCRIPT_DIR / "MOTP"

SOURCE_DIR = PROOLY_ROOT / "11rmo" / "pdf"

# Source filename -> destination directory
PDF_MAP = {
    "alg_yr.pdf": MOTP_ROOT / "assets/pdf/Algebra",
    "alg_topic.pdf": MOTP_ROOT / "assets/pdf/Algebra",

    "comb_yr.pdf": MOTP_ROOT / "assets/pdf/Combinatorics",
    "comb_topic.pdf": MOTP_ROOT / "assets/pdf/Combinatorics",

    "geo_yr.pdf": MOTP_ROOT / "assets/pdf/Geometry",
    "geo_topic.pdf": MOTP_ROOT / "assets/pdf/Geometry",

    "nt_yr.pdf": MOTP_ROOT / "assets/pdf/NumberTheory",
    "nt_topic.pdf": MOTP_ROOT / "assets/pdf/NumberTheory",
}


# ============================================================
# Terminal colors
# ============================================================

RED = "\033[91m"
GREEN = "\033[92m"
MAGENTA = "\033[95m"
CYAN = "\033[96m"
RESET = "\033[0m"


# ============================================================
# Hashing
# ============================================================

def sha256_file(path: Path) -> str:
    """Return the SHA-256 hash of a file's contents."""

    digest = hashlib.sha256()

    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)

    return digest.hexdigest()


# ============================================================
# Replacement logic
# ============================================================

def replace_pdfs(apply: bool):
    """Compare and optionally replace the configured subject PDFs."""

    replaced = 0
    identical = 0
    missing_source = 0
    missing_destination = 0

    replaced_files = []

    # --------------------------------------------------------
    # Compare source and destination PDFs
    # --------------------------------------------------------

    for filename, destination_dir in PDF_MAP.items():

        src = SOURCE_DIR / filename
        dst = destination_dir / filename

        print(f"\nSource:      {src}")
        print(f"Destination: {dst}")

        # Source PDF does not exist.
        if not src.is_file():
            missing_source += 1
            print(
                f"  {RED}[MISSING SOURCE]{RESET} "
                f"{filename}"
            )
            continue

        # Destination PDF does not exist.
        if not dst.is_file():
            missing_destination += 1
            print(
                f"  {RED}[SKIP]{RESET} "
                f"{filename} (not in destination)"
            )
            continue

        # Compare actual file contents.
        if sha256_file(src) == sha256_file(dst):
            identical += 1
            print(
                f"  {CYAN}[UNCHANGED]{RESET} "
                f"{filename} (identical)"
            )
            continue

        # Contents differ.
        replaced += 1
        replaced_files.append(dst)

        print(
            f"  {GREEN}[REPLACE]{RESET} "
            f"{filename} (content differs)"
        )

        if apply:
            shutil.copy2(src, dst)

    # --------------------------------------------------------
    # Report destination-only PDFs
    # --------------------------------------------------------

    print("\nDestination-only PDFs:")

    destination_only = 0

    for destination_dir in dict.fromkeys(PDF_MAP.values()):

        expected_names = {
            filename
            for filename, mapped_dir in PDF_MAP.items()
            if mapped_dir == destination_dir
        }

        if not destination_dir.is_dir():
            continue

        for dst in sorted(destination_dir.glob("*.pdf")):
            if dst.name not in expected_names:
                destination_only += 1
                print(
                    f"  {MAGENTA}[PRESERVED]{RESET} {dst}"
                )

    return (
        replaced,
        identical,
        missing_source,
        missing_destination,
        destination_only,
        replaced_files,
    )


# ============================================================
# Main
# ============================================================

def main() -> int:

    parser = argparse.ArgumentParser(
        description=(
            "Replace subject-wise MOTP PDFs using "
            "PDFs generated by the RMO build."
        )
    )

    parser.add_argument(
        "--apply",
        action="store_true",
        help=(
            "Actually copy differing PDFs. Without this flag, "
            "only preview changes."
        ),
    )

    args = parser.parse_args()

    mode = "APPLY" if args.apply else "DRY RUN"

    print("=" * 60)
    print("MOTP SUBJECT PDF UPDATE")
    print("=" * 60)
    print(f"Mode:        {mode}")
    print(f"Source:      {SOURCE_DIR}")
    print(f"Destination: {MOTP_ROOT / 'assets/pdf'}")

    if not SOURCE_DIR.is_dir():
        print(
            f"\nERROR: Source directory does not exist: {SOURCE_DIR}",
            file=sys.stderr,
        )
        return 1

    try:
        (
            replaced,
            identical,
            missing_source,
            missing_destination,
            destination_only,
            replaced_files,
        ) = replace_pdfs(args.apply)

    except OSError as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        return 1

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print("\n" + "=" * 60)
    print("Summary")
    print("=" * 60)

    print(f"  PDFs to replace / replaced:       {replaced}")

    for path in replaced_files:
        print(f"    {path}")

    print(f"  PDFs skipped (identical):         {identical}")
    print(f"  PDFs missing from source:         {missing_source}")
    print(f"  PDFs absent from destination:     {missing_destination}")
    print(f"  PDFs present only in destination: {destination_only}")

    if not args.apply:
        print("\nDry run only. No files were copied.")
        print("Run with --apply to perform the replacements.")
    else:
        print("\nSubject PDF replacement completed.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
